"""Unit tests for the pure parts of scripts/check_lock.py (no network, no subprocess)."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "check_lock.py"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("check_lock", _SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolve annotations via sys.modules, so register before executing.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


check_lock = _load()

LOCK_TEXT = """\
#
# This file is autogenerated by pip-compile
#
Annotated_Types==0.8.0 \\
    --hash=sha256:aaa \\
    --hash=sha256:bbb
    # via pydantic
pip==26.2.2 \\
    --hash=sha256:ccc
    # via pip-api
zope.interface==7.0 \\
    --hash=sha256:ddd
"""


def test_parse_lock_normalises_names_and_reads_versions() -> None:
    assert check_lock.parse_lock(LOCK_TEXT) == {
        "annotated-types": "0.8.0",
        "pip": "26.2.2",
        "zope-interface": "7.0",
    }


def test_parse_lock_ignores_comments_and_hash_lines() -> None:
    assert check_lock.parse_lock("# pydantic==1.0\n    --hash=sha256:x\n") == {}


def test_real_lock_parses_and_pins_pip() -> None:
    pins = check_lock.parse_lock(check_lock.LOCK.read_text(encoding="utf-8"))
    assert pins["pip"]
    assert pins["pydantic"]
    assert len(pins) >= 40


def test_compare_clean() -> None:
    drift = check_lock.compare({"a": "1", "b": "2"}, {"a": "1", "b": "2"})
    assert drift.clean


@pytest.mark.parametrize(
    ("locked", "resolved", "field", "expected"),
    [
        ({"a": "1", "old": "3"}, {"a": "1"}, "obsolete", {"old": "3"}),
        ({"a": "1"}, {"a": "1", "new": "4"}, "missing", {"new": "4"}),
        ({"a": "1"}, {"a": "2"}, "mismatched", {"a": ("1", "2")}),
    ],
)
def test_compare_reports_each_kind_of_drift(
    locked: dict[str, str], resolved: dict[str, str], field: str, expected: object
) -> None:
    drift = check_lock.compare(locked, resolved)
    assert not drift.clean
    assert getattr(drift, field) == expected


@pytest.mark.parametrize(
    ("raw", "normalised"),
    [
        ("Pydantic_Core", "pydantic-core"),
        ("zope.interface", "zope-interface"),
        ("a--b__c", "a-b-c"),
    ],
)
def test_normalize(raw: str, normalised: str) -> None:
    assert check_lock.normalize(raw) == normalised
